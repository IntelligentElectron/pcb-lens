/**
 * The agent skill for the query command line, rendered from the tool registry.
 *
 * The skill follows the Agent Skills specification (agentskills.io): one
 * `SKILL.md` with the command line's usage and every tool's description and
 * flags, which an agent reads before running a tool. It is this module's
 * output, written by `npm run gen:skill`. A test compares it with the
 * committed file, so a change to a tool's description or arguments fails until
 * the skill is regenerated, and the skill never describes a tool other than the
 * one that runs.
 */

import { GITHUB_REPO, NPM_PACKAGE } from "./version.js";
import { TOOLS } from "../tools/index.js";
import { flagsOf, positionalOf } from "./query.js";

/** The skill's directory, from the repository root. */
export const SKILL_DIR = "plugins/pcb-lens/skills/pcb-lens";

/** Where the generated skill lives, from the repository root. */
export const SKILL_PATH = `${SKILL_DIR}/SKILL.md`;

const GENERATED =
  "<!-- Generated by `npm run gen:skill` from the tool registry in src/tools/index.ts. Edit the tools, not this file. -->";

const SKILL_DESCRIPTION =
  "Query PCB layouts from the shell with the pcb-lens command line: IPC-2581 XML from any EDA " +
  "tool, and Cadence Allegro .brd boards and Constraint Manager .dcf/.tcfx files for design " +
  "rules. Gives the layer stackup, component placement and pads, net routing (trace widths, " +
  "lengths, vias), and the constraint sets, net classes, diff pairs and match groups. Use when " +
  "reviewing a PCB layout and no pcb-lens MCP server is connected, as in a sandbox or container.";

/**
 * The skill's frontmatter: the Agent Skills fields, and only those, so every
 * host reads it. Each value is written as a JSON string, which is a YAML
 * double-quoted scalar, because a plain one cannot hold the `: ` the
 * description does and strict YAML readers (gh skill) refuse it.
 */
const FRONTMATTER = {
  name: "pcb-lens",
  description: SKILL_DESCRIPTION,
  license: "Apache-2.0",
  compatibility:
    "Requires a shell and the pcb-lens command line (the standalone binary, or Node.js 24+ for npx).",
};

const flagLine = (flag: ReturnType<typeof flagsOf>[number], positional?: string): string => {
  const kind = flag.kind === "boolean" ? "true or false; alone means true" : flag.kind;
  const notes = [kind];
  if (flag.required) notes.unshift("required");
  if (flag.default !== undefined) notes.push(`default ${JSON.stringify(flag.default)}`);
  if (flag.name === positional) notes.push("may be the first argument");
  const description = flag.description ? ` ${flag.description}.`.replace(/\.\.$/, ".") : "";
  return `- \`--${flag.name}\` (${notes.join("; ")}).${description}`;
};

/** The skill's Markdown. */
export const renderSkill = (): string => {
  const lines: string[] = [
    "---",
    ...Object.entries(FRONTMATTER).map(([key, value]) => `${key}: ${JSON.stringify(value)}`),
    "---",
    "",
    GENERATED,
    "",
    "# PCB Lens command line",
    "",
    "`pcb-lens` answers the same queries as the pcb-lens MCP server, one shell command each. When that MCP server is connected, use its tools instead.",
    "",
    "## Install",
    "",
    "Check for it with `pcb-lens --version`. If it is missing, either install the standalone binary:",
    "",
    "```bash",
    `curl -fsSL https://raw.githubusercontent.com/${GITHUB_REPO}/main/install.sh | bash`,
    "```",
    "",
    "or run it through npm without installing, writing `npx -y " +
      NPM_PACKAGE +
      "` wherever this guide writes `pcb-lens`.",
    "",
    "## Usage",
    "",
    "```bash",
    "pcb-lens <tool> [file] --flag value ...",
    "pcb-lens <tool> --help     # the tool's description and every flag",
    "pcb-lens --help            # every tool",
    "```",
    "",
    "- The tool is its name below, in snake_case. Flags are its arguments, spelled exactly.",
    "- The file the tool reads may be the first argument, or its flag (`--file`, or `--board` on the export tools).",
    "- A flag takes the next word, or `--flag=value`. A value that starts with a dash needs `=`: `--pattern=-12V`.",
    "- Quote regex patterns for the shell: `--pattern '^VCC'`.",
    "",
    "## Output and exit codes",
    "",
    "The result is the tool's JSON on stdout: indented in a terminal, one compact line otherwise, so pipe it to `jq` when it is long.",
    "",
    "| Exit | Meaning |",
    "|------|---------|",
    "| 0 | The result answers the query |",
    "| 1 | The result has an `error` field: a missing file, no match, an invalid pattern |",
    "| 2 | Usage error: an unknown or missing flag, or a value of the wrong kind. The message and a usage line are on stderr |",
    "",
    "## Workflow",
    "",
    "1. `get_pcb_metadata` on an IPC-2581 file gives the layer stackup, units and size of the design.",
    "2. `get_pcb_component` looks up one component by exact refdes; `get_pcb_net` traces nets by regex.",
    "3. `get_constraints` on a .brd, .dcf or .tcfx file gives the design rules: without `--section` an overview of the sections, with it the objects of one section.",
    "4. On Windows with Cadence installed, `export_cadence_ipc2581` turns a .brd into the IPC-2581 file the first two steps read.",
    "",
    "```bash",
    "pcb-lens get_pcb_metadata board.xml",
    "pcb-lens get_pcb_net board.xml --pattern '^DDR_D[0-7]$'",
    "pcb-lens get_constraints board.brd --section BrdPhysicalCSet",
    "```",
    "",
    "## Conventions",
    "",
    "- Lengths, coordinates and trace widths from the IPC-2581 tools are in microns, whatever the file's own unit; rotation is in degrees counterclockwise",
    "- A constraint section's `units` field names the unit of its lengths",
    "- Read layout files only through these commands, not by parsing them yourself, and never run `pcb-lens update` or `pcb-lens uninstall`: they replace or remove the binary",
    "",
    "## Tools",
    "",
    "Each description is the MCP tool's own.",
  ];
  for (const tool of TOOLS) {
    const positional = positionalOf(tool);
    lines.push("", `### ${tool.name}`, "", tool.description, "");
    lines.push(...flagsOf(tool).map((flag) => flagLine(flag, positional)));
  }
  return `${lines.join("\n")}\n`;
};
